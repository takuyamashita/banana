//! 勤怠(timesheet)の業務。
//!
//! 派遣社員が、案件ごとの毎日の稼働を月ごとの勤務表に書いて申告し、管理者が確かめて承認する。
//! 承認された稼働は、給与の計算(給与明細の明細行)の元になる。
//! - 派遣社員(staff)と案件(project): 給与(payroll)で登録されたものの写し。勤怠では変えない
//! - 勤務表(timesheet): 派遣社員1人の、ある1か月分の稼働。作成中・申告済み・承認済みのどれか
//!
//! それぞれは番号で互いを指し、ほかのものの中身を直接は持たない

